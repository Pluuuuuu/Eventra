package com.eventra.model;

// Import Java time classes for handling date and time information
// LocalDateTime: Represents a date and time without timezone information
// Used for storing event start/end times and audit timestamps
import java.time.LocalDateTime;
// LocalDate: Represents a date without time information
// Used for extracting just the date portion from event times
import java.time.LocalDate;

/**
 * Event Model Class for Eventra Event Management System
 * 
 * This class represents an event in the system. It contains all the information
 * needed to describe, schedule, and manage events. Events can be created by
 * administrators and staff, and attendees can register for them.
 * 
 * Key Features:
 * - Event scheduling and timing information
 * - Event details and descriptions
 * - Attendee capacity management
 * - Event status tracking
 * - Organizer assignment
 * 
 * File Usage: Used by EventDAO for database operations, controllers for event management,
 * and throughout the application for displaying and managing events
 * 
 * DESIGN PATTERN: This class implements the JavaBean pattern with private fields
 * and public getter/setter methods, plus helper methods for business logic.
 */
public class Event {
    // Event identification and basic information
    // These fields store the core event details and scheduling information
    private int eventId;                   // Unique identifier for the event (primary key)
    // Auto-generated by database, used for database relationships and event identification
    private String title;                  // Event title/name
    // Human-readable name of the event, displayed in UI and reports
    private String description;            // Detailed description of the event
    // Full description including agenda, speakers, requirements, etc.
    private LocalDateTime startDateTime;   // When the event starts
    // Precise start time including date and time, used for scheduling
    private LocalDateTime endDateTime;     // When the event ends
    // Precise end time including date and time, used for scheduling and duration calculation
    private String location;               // Event location/venue
    // Physical location or virtual meeting link for the event
    private String imageUrl;               // URL to event image/banner
    // Optional promotional image for the event, displayed in event listings
    
    // Event management and status information
    // These fields handle event administration and capacity management
    private int eventStatusTypeId;         // Event status (references EventStatusType table)
    // Foreign key to EventStatusType table, determines if event is Draft, Published, etc.
    private int organizerId;               // User ID of the event organizer (foreign key to UserM table)
    // Foreign key to UserM table, identifies who created/manages this event
    private int maxAttendees;              // Maximum number of attendees allowed
    // Capacity limit for the event, 0 means unlimited capacity
    private int currentAttendees;          // Current number of registered attendees
    // Running count of attendees who have registered for this event
    private String eventType;              // Type/category of the event
    // Classification of event (Conference, Workshop, Seminar, etc.)
    
    // Audit and tracking information
    // These fields track when the event was created and last modified
    private LocalDateTime createdAt;       // When the event was created
    // Set automatically when event is first created
    private LocalDateTime updatedAt;       // When the event was last updated
    // Updated automatically whenever event information is modified

    /**
     * Default constructor - creates an empty event object
     * Used when creating new events or loading from database
     * 
     * PURPOSE: This constructor is required for:
     * - Database mapping frameworks (like JDBC ResultSet mapping)
     * - Serialization/deserialization (JSON, XML)
     * - Creating event objects before setting all fields
     */
    public Event() {}

    /**
     * Constructor with basic event information
     * Creates a new event with default status (Published) and no attendees
     * 
     * @param title Event title/name
     * @param description Event description
     * @param startDateTime When the event starts
     * @param endDateTime When the event ends
     * @param location Event location
     * @param organizerId User ID of the event organizer
     * 
     * DEFAULT VALUES:
     * - eventStatusTypeId = 2 (Published status - event is visible to attendees)
     * - currentAttendees = 0 (Start with no attendees)
     * - maxAttendees = 0 (Unlimited capacity by default)
     */
    public Event(String title, String description, LocalDateTime startDateTime, 
                LocalDateTime endDateTime, String location, int organizerId) {
        // Set the provided event information
        this.title = title;                // Store the event title
        this.description = description;    // Store the event description
        this.startDateTime = startDateTime; // Store the start date/time
        this.endDateTime = endDateTime;    // Store the end date/time
        this.location = location;          // Store the event location
        this.organizerId = organizerId;    // Store the organizer's user ID
        
        // Set default values for event management
        this.eventStatusTypeId = 2; // Published by default - event is visible to attendees
        // Status 2 = Published, making the event immediately available for registration
        this.currentAttendees = 0; // Start with no attendees
        // New events start with zero registrations
    }

    // Getters and Setters - provide access to private fields
    // These methods allow other classes to read and modify event information
    // Following JavaBean convention for compatibility with frameworks
    
    // Event ID getter and setter
    public int getEventId() { return eventId; }
    // Returns the unique event identifier
    public void setEventId(int eventId) { this.eventId = eventId; }
    // Sets the unique event identifier (usually called by database mapping)

    // Title getter and setter
    public String getTitle() { return title; }
    // Returns the event title
    public void setTitle(String title) { this.title = title; }
    // Sets the event title

    // Description getter and setter
    public String getDescription() { return description; }
    // Returns the event description
    public void setDescription(String description) { this.description = description; }
    // Sets the event description

    // Start date/time getter and setter
    public LocalDateTime getStartDateTime() { return startDateTime; }
    // Returns when the event starts
    public void setStartDateTime(LocalDateTime startDateTime) { this.startDateTime = startDateTime; }
    // Sets when the event starts

    // End date/time getter and setter
    public LocalDateTime getEndDateTime() { return endDateTime; }
    // Returns when the event ends
    public void setEndDateTime(LocalDateTime endDateTime) { this.endDateTime = endDateTime; }
    // Sets when the event ends

    // Location getter and setter
    public String getLocation() { return location; }
    // Returns the event location
    public void setLocation(String location) { this.location = location; }
    // Sets the event location

    // Image URL getter and setter
    public String getImageUrl() { return imageUrl; }
    // Returns the URL to the event image
    public void setImageUrl(String imageUrl) { this.imageUrl = imageUrl; }
    // Sets the URL to the event image

    // Event status type ID getter and setter
    public int getEventStatusTypeId() { return eventStatusTypeId; }
    // Returns the event status identifier
    public void setEventStatusTypeId(int eventStatusTypeId) { this.eventStatusTypeId = eventStatusTypeId; }
    // Sets the event status identifier

    // Organizer ID getter and setter
    public int getOrganizerId() { return organizerId; }
    // Returns the organizer's user ID
    public void setOrganizerId(int organizerId) { this.organizerId = organizerId; }
    // Sets the organizer's user ID

    // Max attendees getter and setter
    public int getMaxAttendees() { return maxAttendees; }
    // Returns the maximum number of attendees allowed
    public void setMaxAttendees(int maxAttendees) { this.maxAttendees = maxAttendees; }
    // Sets the maximum number of attendees allowed

    // Current attendees getter and setter
    public int getCurrentAttendees() { return currentAttendees; }
    // Returns the current number of registered attendees
    public void setCurrentAttendees(int currentAttendees) { this.currentAttendees = currentAttendees; }
    // Sets the current number of registered attendees

    // Event type getter and setter
    public String getEventType() { return eventType; }
    // Returns the event type/category
    public void setEventType(String eventType) { this.eventType = eventType; }
    // Sets the event type/category

    // Created timestamp getter and setter
    public LocalDateTime getCreatedAt() { return createdAt; }
    // Returns when the event was created
    public void setCreatedAt(LocalDateTime createdAt) { this.createdAt = createdAt; }
    // Sets when the event was created

    // Updated timestamp getter and setter
    public LocalDateTime getUpdatedAt() { return updatedAt; }
    // Returns when the event was last updated
    public void setUpdatedAt(LocalDateTime updatedAt) { this.updatedAt = updatedAt; }
    // Sets when the event was last updated

    // Helper methods - provide convenient ways to access and manipulate event data
    // These methods encapsulate business logic and provide useful functionality
    
    /**
     * Get the date of the event (without time)
     * 
     * @return LocalDate object representing the event date, or null if startDateTime is null
     * 
     * PURPOSE: This method extracts just the date portion from the event start time.
     * Useful for:
     * - Date-based filtering and sorting
     * - Calendar displays
     * - Date comparisons without time considerations
     * 
     * LOGIC: Converts LocalDateTime to LocalDate using toLocalDate() method
     */
    public LocalDate getEventDate() {
        return startDateTime != null ? startDateTime.toLocalDate() : null;
        // If startDateTime exists, extract just the date portion
        // If startDateTime is null, return null to avoid NullPointerException
    }

    /**
     * Check if the event is published and available for registration
     * 
     * @return true if event status is "Published" (status ID = 2)
     * 
     * PURPOSE: This method determines if the event is visible and bookable by attendees.
     * Used for:
     * - Filtering events in attendee views
     * - Controlling registration availability
     * - Event listing displays
     * 
     * NOTE: The method name "isComingSoon" might be misleading - it actually checks
     * if the event is published, not if it's coming soon.
     */
    public boolean isComingSoon() {
        return eventStatusTypeId == 2; // Published status - event is visible and bookable
        // Status ID 2 corresponds to "Published" in the EventStatusType table
        // Published events are visible to attendees and allow registration
    }

    /**
     * Check if the event has available spots for registration
     * 
     * @return true if event has unlimited capacity or current attendees < max attendees
     * 
     * PURPOSE: This method determines if new attendees can register for the event.
     * Used for:
     * - Enabling/disabling registration buttons
     * - Displaying capacity status
     * - Registration validation
     * 
     * LOGIC:
     * - If maxAttendees is 0, capacity is unlimited (always available)
     * - Otherwise, check if current attendees is less than maximum
     */
    public boolean hasAvailableSpots() {
        return maxAttendees == 0 || currentAttendees < maxAttendees;
        // maxAttendees == 0: Unlimited capacity (always available)
        // currentAttendees < maxAttendees: Still has available spots
    }

    /**
     * Get the number of available spots for registration
     * 
     * @return Number of available spots, or Integer.MAX_VALUE if unlimited capacity
     * 
     * PURPOSE: This method provides the exact number of remaining spots.
     * Used for:
     * - Displaying capacity information to users
     * - Capacity planning and reporting
     * - Registration limit enforcement
     * 
     * LOGIC:
     * - If maxAttendees is 0, return Integer.MAX_VALUE (unlimited)
     * - Otherwise, return the difference between max and current attendees
     */
    public int getAvailableSpots() {
        return maxAttendees == 0 ? Integer.MAX_VALUE : maxAttendees - currentAttendees;
        // maxAttendees == 0: Return Integer.MAX_VALUE for unlimited capacity
        // Otherwise: Calculate remaining spots (max - current)
    }

    /**
     * String representation of the event for debugging and logging
     * 
     * @return String containing key event information
     * 
     * PURPOSE: This method provides a human-readable representation of the event.
     * Used for:
     * - Debugging and logging
     * - Console output
     * - Error messages
     * 
     * OVERRIDE: This overrides the default toString() method from Object class
     * to provide more meaningful output for Event objects.
     */
    @Override
    public String toString() {
        return "Event{" +
                "eventId=" + eventId +                    // Include event ID
                ", title='" + title + '\'' +              // Include event title
                ", startDateTime=" + startDateTime +      // Include start time
                ", location='" + location + '\'' +        // Include location
                ", organizerId=" + organizerId +          // Include organizer ID
                '}';
        // Returns a formatted string with key event information
        // Uses single quotes around string values for clarity
    }
}

