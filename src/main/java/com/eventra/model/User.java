package com.eventra.model;

// Import Java time classes for handling date and time information
// LocalDateTime: Represents a date and time without timezone information
// Used for storing timestamps like creation dates, last login times, etc.
import java.time.LocalDateTime;

/**
 * User Model Class for Eventra Event Management System
 * 
 * This class represents a user account in the system. It contains all the
 * information needed to identify, authenticate, and manage user accounts.
 * Users can have different roles (SuperAdmin, Admin, Staff, Attendee) and
 * different statuses (Active, Inactive, Suspended, Deleted).
 * 
 * Key Features:
 * - User authentication and authorization data
 * - Role-based access control
 * - Account status management
 * - Login attempt tracking
 * - Profile information storage
 * 
 * File Usage: Used by UserDAO for database operations, controllers for user management,
 * and throughout the application for user authentication and authorization
 * 
 * DESIGN PATTERN: This class implements the JavaBean pattern with private fields
 * and public getter/setter methods, making it compatible with database mapping
 * and serialization frameworks.
 */
public class User {
    // Role constants - define the different user roles in the system
    // These values correspond to the RoleType table in the database
    // Using constants prevents magic numbers and makes the code more readable
    public static final int ROLE_SUPER_ADMIN = 1;  // Highest privilege level - can manage everything
    // SuperAdmin has full system access including user management, system settings
    public static final int ROLE_ADMIN = 2;        // Can manage events and users
    // Admin can create/edit events, manage attendees, view reports
    public static final int ROLE_STAFF = 3;        // Can manage specific events and attendees
    // Staff can manage assigned events and handle attendee registrations
    public static final int ROLE_ATTENDEE = 4;     // Basic user - can register for events
    // Attendee can view events, register for events, manage their profile
    
    // User identification and basic information
    // These fields store the core user identity and personal information
    private int userId;                    // Unique identifier for the user (primary key)
    // Auto-generated by database, used for database relationships
    private String username;               // Unique username for login
    // User-chosen login name, must be unique across all users
    private String firstName;              // User's first name
    // Required field for user identification
    private String middleName;             // User's middle name (optional)
    // Optional field, can be null or empty
    private String lastName;               // User's last name
    // Required field for user identification
    private String email;                  // User's email address (unique)
    // Primary contact method, used for password reset and notifications
    
    // Authentication and security information
    // These fields handle user authentication and security features
    private String passwordHash;           // Hashed password for security
    // BCrypt hashed password, never stored as plain text
    private String profilePicUrl;          // URL to user's profile picture
    // Optional field, can be null if user hasn't uploaded a picture
    private int roleTypeId;                // User's role (references RoleType table)
    // Foreign key to RoleType table, determines user permissions
    private int statusTypeId;              // User's status (references StatusType table)
    // Foreign key to StatusType table, determines if user can login
    private int periodCanLoginInMinutes;   // Time period user can login (for temporary access)
    // Used for temporary access accounts, 0 means no restriction
    private LocalDateTime lastFailedLoginAt; // Timestamp of last failed login attempt
    // Used for security monitoring and account lockout features
    
    // Audit and tracking information
    // These fields track when the user account was created and last modified
    private LocalDateTime createdAt;       // When the user account was created
    // Set automatically when user is first created
    private LocalDateTime updatedAt;       // When the user account was last updated
    // Updated automatically whenever user information is modified

    /**
     * Default constructor - creates an empty user object
     * Used when creating new users or loading from database
     * 
     * PURPOSE: This constructor is required for:
     * - Database mapping frameworks (like JDBC ResultSet mapping)
     * - Serialization/deserialization (JSON, XML)
     * - Creating user objects before setting all fields
     */
    public User() {}

    /**
     * Constructor with basic user information
     * Creates a new user with default role (Attendee) and status (Active)
     * 
     * @param username Unique username for the user
     * @param firstName User's first name
     * @param lastName User's last name
     * @param email User's email address
     * @param passwordHash Hashed password for security
     * 
     * DEFAULT VALUES:
     * - roleTypeId = 4 (Attendee role - most restrictive)
     * - statusTypeId = 1 (Active status - user can login)
     * - periodCanLoginInMinutes = 0 (No time restriction)
     */
    public User(String username, String firstName, String lastName, String email, String passwordHash) {
        // Set the provided user information
        this.username = username;          // Store the unique username
        this.firstName = firstName;        // Store the first name
        this.lastName = lastName;          // Store the last name
        this.email = email;                // Store the email address
        this.passwordHash = passwordHash;  // Store the hashed password
        
        // Set default values for security and access control
        this.roleTypeId = 4; // Default role (Attendees) - most restrictive
        // New users start with the least privileged role for security
        this.statusTypeId = 1; // Default status (Active) - user can login
        // New users are active by default, allowing immediate login
        this.periodCanLoginInMinutes = 0; // No time restriction on login
        // 0 means no time restriction, user can login anytime
    }

    // Getters and Setters - provide access to private fields
    // These methods allow other classes to read and modify user information
    // Following JavaBean convention for compatibility with frameworks
    
    // User ID getter and setter
    public int getUserId() { return userId; }
    // Returns the unique user identifier
    public void setUserId(int userId) { this.userId = userId; }
    // Sets the unique user identifier (usually called by database mapping)

    // Username getter and setter
    public String getUsername() { return username; }
    // Returns the user's login username
    public void setUsername(String username) { this.username = username; }
    // Sets the user's login username

    // First name getter and setter
    public String getFirstName() { return firstName; }
    // Returns the user's first name
    public void setFirstName(String firstName) { this.firstName = firstName; }
    // Sets the user's first name

    // Middle name getter and setter
    public String getMiddleName() { return middleName; }
    // Returns the user's middle name (can be null)
    public void setMiddleName(String middleName) { this.middleName = middleName; }
    // Sets the user's middle name (can be null)

    // Last name getter and setter
    public String getLastName() { return lastName; }
    // Returns the user's last name
    public void setLastName(String lastName) { this.lastName = lastName; }
    // Sets the user's last name

    // Email getter and setter
    public String getEmail() { return email; }
    // Returns the user's email address
    public void setEmail(String email) { this.email = email; }
    // Sets the user's email address

    // Password hash getter and setter
    public String getPasswordHash() { return passwordHash; }
    // Returns the BCrypt hashed password
    public void setPasswordHash(String passwordHash) { this.passwordHash = passwordHash; }
    // Sets the BCrypt hashed password

    // Profile picture URL getter and setter
    public String getProfilePicUrl() { return profilePicUrl; }
    // Returns the URL to the user's profile picture
    public void setProfilePicUrl(String profilePicUrl) { this.profilePicUrl = profilePicUrl; }
    // Sets the URL to the user's profile picture

    // Role type ID getter and setter
    public int getRoleTypeId() { return roleTypeId; }
    // Returns the user's role identifier
    public void setRoleTypeId(int roleTypeId) { this.roleTypeId = roleTypeId; }
    // Sets the user's role identifier

    // Status type ID getter and setter
    public int getStatusTypeId() { return statusTypeId; }
    // Returns the user's status identifier
    public void setStatusTypeId(int statusTypeId) { this.statusTypeId = statusTypeId; }
    // Sets the user's status identifier

    // Login period getter and setter
    public int getPeriodCanLoginInMinutes() { return periodCanLoginInMinutes; }
    // Returns the time period (in minutes) the user can login
    public void setPeriodCanLoginInMinutes(int periodCanLoginInMinutes) { this.periodCanLoginInMinutes = periodCanLoginInMinutes; }
    // Sets the time period (in minutes) the user can login

    // Last failed login timestamp getter and setter
    public LocalDateTime getLastFailedLoginAt() { return lastFailedLoginAt; }
    // Returns the timestamp of the last failed login attempt
    public void setLastFailedLoginAt(LocalDateTime lastFailedLoginAt) { this.lastFailedLoginAt = lastFailedLoginAt; }
    // Sets the timestamp of the last failed login attempt

    // Created timestamp getter and setter
    public LocalDateTime getCreatedAt() { return createdAt; }
    // Returns when the user account was created
    public void setCreatedAt(LocalDateTime createdAt) { this.createdAt = createdAt; }
    // Sets when the user account was created

    // Updated timestamp getter and setter
    public LocalDateTime getUpdatedAt() { return updatedAt; }
    // Returns when the user account was last updated
    public void setUpdatedAt(LocalDateTime updatedAt) { this.updatedAt = updatedAt; }
    // Sets when the user account was last updated

    /**
     * Helper method to get the user's full name
     * Combines first, middle (if exists), and last name
     * 
     * @return Full name as a string
     * 
     * LOGIC:
     * - If middle name exists and is not empty, include it
     * - Otherwise, return just first and last name
     * - Handles null and empty middle names gracefully
     * 
     * USAGE: Used in UI displays, reports, and user identification
     */
    public String getFullName() {
        if (middleName != null && !middleName.trim().isEmpty()) {
            // Include middle name if it exists and is not empty
            // middleName != null: Check if middle name is not null
            // !middleName.trim().isEmpty(): Check if middle name is not just whitespace
            // trim() removes leading and trailing whitespace
            return firstName + " " + middleName + " " + lastName;
            // Concatenate first, middle, and last name with spaces
        }
        // Return just first and last name if no middle name
        // This handles cases where middle name is null, empty, or just whitespace
        return firstName + " " + lastName;
        // Concatenate first and last name with a space
    }
}

